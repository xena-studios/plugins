// /api/ and /api/<plugin>/: where each developer API's reference is. Dokka's pages replace these
// once the Gradle build writes them; meanwhile they point at the guide and javadoc.io.
import Link from "fumadocs-core/link";
import type * as PageTree from "fumadocs-core/page-tree";
import { DocsLayout } from "fumadocs-ui/layouts/notebook";
import { DocsBody, DocsPage } from "fumadocs-ui/layouts/notebook/page";
import type { ApiInfo } from "../../lib/api.ts";
import { iconOf } from "../icons.ts";
import { baseOptions, docsSlots } from "../layout/shared.tsx";
import { SiteFooter } from "../layout/SiteFooter.tsx";
import { Aside } from "../starlight.tsx";

export function ApiPage({ info }: { info: ApiInfo }) {
  const base = baseOptions();
  const p = info.plugin;
  return (
    <DocsLayout {...base} nav={{ ...base.nav, mode: "top" }}
      slots={docsSlots} tree={info.tree as unknown as PageTree.Root} tabs={false} sidebar={{ collapsible: false }}>
      <DocsPage breadcrumb={{ enabled: false }} footer={{ enabled: true }} slots={{ footer: () => <div className="page-footer"><SiteFooter /></div> }} tableOfContent={{ enabled: false }} tableOfContentPopover={{ enabled: false }}>
        <div className="page-title">
          {p && (
            <span className="gui-slot small-slot">
              <img src={iconOf(p.id)} alt="" width="40" height="40" />
            </span>
          )}
          <div>
            <h1>{p ? `${p.name} API reference` : "API reference"}</h1>
            <p className="page-description">
              {p ? `Every class and method of ${p.name}'s developer API.` : "Every class and method of each plugin's developer API, generated from its code."}
            </p>
          </div>
        </div>
        <DocsBody>
          {p ? (
            <>
              <Aside type="note" title="Generated from the code, soon">
                <p>
                  This page will be {p.name}'s API reference, generated by Dokka from {p.rewritten ? "its Kotlin API" : "its rewrite's Kotlin API"} at every build. Until it is,{" "}
                  <Link href={p.guide}>the developer API guide</Link> covers how to depend on it and use it
                  {p.released ? (
                    <>
                      , and its javadoc is on <a href={`https://javadoc.io/doc/co.xenastudios.${p.id}/${p.id}-api`}>javadoc.io</a>
                    </>
                  ) : null}
                  .
                </p>
              </Aside>
              <ul>
                {p.maven && (
                  <li>
                    Maven coordinates: <code>{`${p.maven}:${p.version}`}</code>
                  </li>
                )}
                {p.unreleasedRewrite && p.newVersion && (
                  <li>
                    The rewrite's API, {p.name} {p.newVersion}, is documented in <Link href={`/${p.id}/next/developer-api/`}>its guide</Link> until it's released.
                  </li>
                )}
                {p.events > 0 && <li>{p.events} events, listed with the guide.</li>}
              </ul>
            </>
          ) : (
            <div className="ref-table">
              <table>
                <thead>
                  <tr>
                    <th>Plugin</th>
                    <th>Reference</th>
                    <th>Guide</th>
                  </tr>
                </thead>
                <tbody>
                  {info.plugins.map((x) => (
                    <tr key={x.id}>
                      <td className="api-plugin">
                        <img src={iconOf(x.id)} alt="" width="24" height="24" />
                        <Link href={`/api/${x.id}/`}>{x.name}</Link>
                      </td>
                      <td>{x.released ? <a href={`https://javadoc.io/doc/co.xenastudios.${x.id}/${x.id}-api`}>Javadoc</a> : "At its first release"}</td>
                      <td>
                        <Link href={x.guide}>Developer API</Link>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </DocsBody>
      </DocsPage>
    </DocsLayout>
  );
}
