// Per-page route data: the sidebar each page shows, its previous and next, and whether it's a
// reading page. The rules are the Starlight site's, kept:
// - The sidebar shows one plugin at a time. On a plugin's pages it's only that plugin's pages
//   (the layout adds a switcher above them); everywhere else it's the start pages, then each
//   category's plugins as one link each, then the rest.
// - A plugin whose docs have more than one major (src/data/versions.json) shows only the pages of
//   the major you're reading: the newest major's are the plugin's folder less its v<old>/ folders,
//   an old major's are its v<old>/ folder.
// - An unreleased plugin's current pages are its v<current>/ folder, served at /<id>/, and its new
//   major's are the rest of its folder, served at /<id>/next/, hidden: in no other page's sidebar,
//   previous or next, search, the sitemap or search engines.
// - Within a folder, pages are ordered by sidebar.order, then by file name; a folder sits where
//   its lowest-ordered page does; each is labelled with sidebar.label, or its title.
// - Home, overviews and download pages aren't reading pages: no contents column, no previous and
//   next, no edit or last-updated line.
// Each plugin's pages also wear its accent (public/accents/<id>.css, written by pnpm catalog).
import catalog from "./data/plugins.json" with { type: "json" };
import { type DocsPlugin, docsPlugins, majorOf, pluginOf } from "./plugins.ts";

/** The sidebar, as Fumadocs' page tree with plain-text names, so it travels as JSON. */
export interface TreeItem {
  type: "page";
  name: string;
  url: string;
  external?: boolean;
  /** A badge, such as "Soon". */
  description?: string;
}
export interface TreeFolder {
  type: "folder";
  name: string;
  defaultOpen?: boolean;
  index?: TreeItem;
  children: TreeNode[];
}
export interface TreeSeparator {
  type: "separator";
  name: string;
}
export type TreeNode = TreeItem | TreeFolder | TreeSeparator;
export interface Tree {
  name: string;
  children: TreeNode[];
}

/** A page as the sidebar needs it. */
export interface SidebarPage {
  /** Its file, relative to src/content/docs, without the extension: "xutilities/v2/commands". */
  file: string;
  /** Where it's served: "/xutilities/commands/". */
  url: string;
  label: string;
  order: number | undefined;
  hidden: boolean;
  badge?: string;
}

/** The route id Starlight gave a page: its address without slashes ("" for home). */
export const routeIdOf = (url: string) => url.replace(/^\/|\/$/g, "");

interface Dir {
  pages: Map<string, SidebarPage>;
  dirs: Map<string, Dir>;
}
const orderOf = (entry: SidebarPage | Dir): number =>
  "file" in entry ? (entry.order ?? Number.MAX_VALUE) : Math.min(...[...entry.pages.values(), ...entry.dirs.values()].map(orderOf));

/** Starlight's autogenerated group for the pages under [base], as a page tree. */
function autogenerate(pages: SidebarPage[], base: string, exclude: (rest: string) => boolean): TreeNode[] {
  const root: Dir = { pages: new Map(), dirs: new Map() };
  for (const page of pages) {
    if (page.hidden) continue;
    const prefix = base ? `${base}/` : "";
    if (page.file !== `${base}/index` && !page.file.startsWith(prefix)) continue;
    const rest = page.file.slice(prefix.length);
    if (exclude(rest)) continue;
    const parts = rest.split("/");
    let dir = root;
    for (const part of parts.slice(0, -1)) {
      if (!dir.dirs.has(part)) dir.dirs.set(part, { pages: new Map(), dirs: new Map() });
      dir = dir.dirs.get(part)!;
    }
    dir.pages.set(parts.at(-1)!, page);
  }
  const toNodes = (dir: Dir): TreeNode[] =>
    [...[...dir.pages].map(([k, v]) => [k, v] as const), ...[...dir.dirs].map(([k, v]) => [k, v] as const)]
      .sort(([ka, a], [kb, b]) => orderOf(a) - orderOf(b) || ka.localeCompare(kb))
      .map(([key, entry]): TreeNode =>
        "file" in entry
          ? { type: "page", name: entry.label, url: entry.url, ...(entry.badge ? { description: entry.badge } : {}) }
          : { type: "folder", name: key, defaultOpen: true, children: toNodes(entry) },
      );
  return toNodes(root);
}

const links = (nodes: TreeNode[]): TreeItem[] =>
  nodes.flatMap((n) => (n.type === "page" ? [n] : n.type === "folder" ? [...(n.index ? [n.index] : []), ...links(n.children)] : []));

export interface RouteData {
  tree: Tree;
  plugin?: DocsPlugin;
  /** The catalog plugin whose accent and icon the page wears. */
  catalogId?: string;
  /** Not a reading page: no contents, previous and next, or edit line. */
  bare: boolean;
  hidden: boolean;
  previous?: { name: string; url: string };
  next?: { name: string; url: string };
}

/** The route data of the page at [url], among [pages] (every page on the site). */
export function routeData(url: string, pages: SidebarPage[]): RouteData {
  const id = routeIdOf(url);
  const plugin = pluginOf(id);
  const page = plugin && majorOf(plugin, id);
  const isHome = id === "";
  const bare = isHome || !!(page && (page.rest === "" || page.rest === "download"));
  let children: TreeNode[];
  if (plugin && page) {
    // The files the plugin's pages come from: "xutilities" for a released plugin and an
    // unreleased one's new major, "xutilities/v2" for its old major and an unreleased one's
    // current pages.
    const folderId = plugin.group === plugin.name ? plugin.id : plugin.id.replace(/\/next$/, "");
    const folder = plugin.folder ?? (page.newest ? undefined : `v${page.major}`);
    children = folder
      ? autogenerate(pages, `${folderId}/${folder}`, () => false)
      : autogenerate(pages, folderId, (rest) => /^v\d+(\/|$)/.test(rest));
  } else {
    const start = autogenerate(pages, "start", () => false);
    children = [
      { type: "separator", name: "Start here" },
      ...start,
      ...catalog.categories.flatMap((category): TreeNode[] => [
        { type: "separator", name: category },
        ...catalog.plugins
          .filter((p) => p.category === category)
          .map((p): TreeItem => ({ type: "page", name: p.name, url: p.docs, ...(p.released ? {} : { description: "Soon" }) })),
      ]),
      { type: "separator", name: "Developers" },
      { type: "page", name: "Developer APIs", url: "/developers/" },
      { type: "page", name: "API reference", url: "/api/" },
      { type: "separator", name: "More from Xena Studios" },
      { type: "page", name: "Raptor docs", url: "https://docs.raptorpanel.net", external: true },
      { type: "page", name: "NeoSkript", url: "https://neoskript.dev", external: true, description: "Beta" },
      { type: "page", name: "xenastudios.co", url: "https://xenastudios.co", external: true },
    ];
  }
  const tree: Tree = { name: plugin?.name ?? "Xena Studios Plugins", children };
  let previous: RouteData["previous"];
  let next: RouteData["next"];
  if (!bare) {
    const list = links(children).filter((l) => !l.external);
    const at = list.findIndex((l) => l.url === url);
    if (at >= 0) {
      const name = (l: TreeItem) => String(l.name);
      if (list[at - 1]) previous = { name: name(list[at - 1]!), url: list[at - 1]!.url };
      if (list[at + 1]) next = { name: name(list[at + 1]!), url: list[at + 1]!.url };
    }
  }
  return { tree, plugin, catalogId: plugin?.catalogId, bare, hidden: !!plugin?.hidden, previous, next };
}

